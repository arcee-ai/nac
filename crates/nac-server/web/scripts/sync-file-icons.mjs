const manifest = generateManifest();
const wanted = new Set(ICONS);

const missing = ICONS.filter((name) => !manifest.iconDefinitions[name]);
if (missing.length > 0) {
  throw new Error(
    `Icons missing from material-icon-theme: ${missing.join(", ")}`,
  );
}

/** Upstream keys vary in case; the runtime lookup always compares lowercase. */
const pick = (associations) => {
  const result = {};
  for (const [key, icon] of Object.entries(associations)) {
    if (wanted.has(icon)) result[key.toLowerCase()] = icon;
  }
  const sorted = Object.entries(result).sort(([a], [b]) => (a < b ? -1 : 1));
  return Object.fromEntries(sorted);
};

const byName = pick(manifest.fileNames);
const byExtension = pick(manifest.fileExtensions);

await rm(TARGET_DIR, { recursive: true, force: true });
await mkdir(TARGET_DIR, { recursive: true });

let bytes = 0;
for (const name of [...wanted].sort()) {
  const svg = await readFile(path.join(SOURCE_DIR, `${name}.svg`));
  bytes += svg.byteLength;
  await writeFile(path.join(TARGET_DIR, `${name}.svg`), svg);
}

const serialize = (map) =>
  Object.entries(map)
    .map(([key, icon]) => `  ${JSON.stringify(key)}: ${JSON.stringify(icon)},`)
    .join("\n");

await writeFile(
  MANIFEST_FILE,
  `// Generated by scripts/sync-file-icons.mjs — do not edit by hand.
// Source: material-icon-theme@${require("material-icon-theme/package.json").version} (MIT).

/** Icon rendered for a file no association matches. */
export const FALLBACK_ICON = ${JSON.stringify(FALLBACK_ICON)};

/** Whole file names, lowercased, such as \`dockerfile\` or \`package.json\`. */
export interface FileNameIconMap {
  [name: string]: string;
}

export const ICON_BY_FILE_NAME: FileNameIconMap = {
${serialize(byName)}
};

/** Extensions without the leading dot, lowercased; some span several dots. */
export interface ExtensionIconMap {
  [extension: string]: string;
}

export const ICON_BY_EXTENSION: ExtensionIconMap = {
${serialize(byExtension)}
};
`,
);

const files = await readdir(TARGET_DIR);
console.log(
  `Vendored ${files.length} icons (${(bytes / 1024).toFixed(1)} KB), ` +
    `${Object.keys(byName).length} file names and ` +
    `${Object.keys(byExtension).length} extensions.`,
);
