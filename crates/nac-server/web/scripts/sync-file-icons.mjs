// Copies a curated slice of the Material Icon Theme into the design system.
//
// The upstream theme ships 1250 icons; bundling the lot would add megabytes to
// a `dist/` that is committed to git. Instead this script vendors the icons
// named below, together with every file name and extension the upstream
// manifest maps onto them, so adding a language here also picks up its
// aliases. Re-run it with `npm run sync-file-icons` to refresh the vendored
// copies after bumping `material-icon-theme`.

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { generateManifest } = require("material-icon-theme");

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE_DIR = path.join(
  path.dirname(require.resolve("material-icon-theme/package.json")),
  "icons",
);
const TARGET_DIR = path.resolve(__dirname, "../src/app/atoms/file-icon/icons");
const MANIFEST_FILE = path.resolve(
  __dirname,
  "../src/app/atoms/file-icon/manifest.generated.ts",
);

